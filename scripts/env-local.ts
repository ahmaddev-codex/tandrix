/**
 * Writes .env.local for the local stack from `supabase status`.
 *   pnpm env:local
 * Supabase and URL values are always rewritten from the running stack. Values you've set
 * yourself (META_API_KEY, model IDs, TOKEN_SIGNING_SECRET) are kept on every re-run.
 * Refuses to write anything that points outside this machine.
 */
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const target = join(root, ".env.local");

function parseEnv(path: string): Map<string, string> {
  const out = new Map<string, string>();
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) out.set(m[1]!, m[2]!);
  }
  return out;
}

let status: Record<string, string>;
try {
  status = JSON.parse(
    execFileSync("supabase", ["status", "-o", "json"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }),
  );
} catch {
  console.error("Local Supabase isn't running. Start it with: pnpm db:start");
  process.exit(1);
}

const isLocal = (url: string) => /^https?:\/\/(127\.0\.0\.1|localhost)(:\d+)?(\/|$)/.test(url);
const apiUrl = status.API_URL ?? "";
if (!isLocal(apiUrl) || !status.PUBLISHABLE_KEY || !status.SECRET_KEY) {
  console.error(`Unexpected supabase status (API_URL=${apiUrl}). Not writing .env.local.`);
  process.exit(1);
}

const kept = parseEnv(target);
const example = parseEnv(join(root, ".env.example"));
const keep = (k: string, fallback = "") => kept.get(k) || example.get(k) || fallback;

const apiPort = keep("API_PORT", "8787");
const localApi = `http://localhost:${apiPort}`;

const sections: Array<[string, Array<[string, string]>]> = [
  ["API: environment (the desktop app reads it too)", [["TANDRIX_ENV", "local"]]],
  [
    "API: Meta Model API (server only). Use a separate dev key so local runs never touch production quota or billing.",
    [
      ["META_API_KEY", kept.get("META_API_KEY") ?? ""],
      ["META_API_BASE_URL", keep("META_API_BASE_URL")],
      ["META_MODEL_REASONING", keep("META_MODEL_REASONING")],
      ["META_MODEL_COMPUTER_USE", keep("META_MODEL_COMPUTER_USE")],
      ["META_MODEL_SEGMENTATION", keep("META_MODEL_SEGMENTATION")],
      ["META_MODEL_TRANSCRIBE", keep("META_MODEL_TRANSCRIBE")],
      ["META_TIMEOUT_MS", keep("META_TIMEOUT_MS")],
      ...(kept.get("META_SPEND_LIMIT_USD")
        ? ([["META_SPEND_LIMIT_USD", kept.get("META_SPEND_LIMIT_USD")!]] as Array<[string, string]>)
        : []),
    ],
  ],
  [
    "API: local Supabase (from `supabase status`; fixed local keys, not secrets)",
    [
      ["SUPABASE_URL", apiUrl],
      ["SUPABASE_SECRET_KEY", status.SECRET_KEY],
      ["SUPABASE_PUBLISHABLE_KEY", status.PUBLISHABLE_KEY],
      ["SUPABASE_DB_URL", status.DB_URL ?? ""],
      ["SUPABASE_STUDIO_URL", status.STUDIO_URL ?? ""],
      ["SUPABASE_MAIL_URL", status.MAILPIT_URL ?? status.INBUCKET_URL ?? ""],
    ],
  ],
  [
    "API: server",
    [
      ["API_PORT", apiPort],
      ["API_PUBLIC_URL", localApi],
      // The Mac app's dev server and built app always need access; other origins are kept.
      [
        "CORS_ORIGINS",
        [
          ...new Set([
            ...keep("CORS_ORIGINS").split(",").filter(Boolean),
            "http://localhost:5173",
            "app://tandrix",
          ]),
        ].join(","),
      ],
      [
        "TOKEN_SIGNING_SECRET",
        kept.get("TOKEN_SIGNING_SECRET") || randomBytes(32).toString("base64"),
      ],
    ],
  ],
  ["Website (Next.js): reads Vercel or apps/web/.env.local, not this file", []],
  [
    "Mobile (Expo): the app reads its copy in apps/mobile/.env.local. A physical phone can't reach 127.0.0.1: replace with this Mac's LAN IP to test on device.",
    [
      ["EXPO_PUBLIC_API_URL", localApi],
      ["EXPO_PUBLIC_SUPABASE_URL", apiUrl],
      ["EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY", status.PUBLISHABLE_KEY],
    ],
  ],
  [
    "Desktop (Electron, Vite)",
    [
      ["VITE_API_URL", localApi],
      ["VITE_SUPABASE_URL", apiUrl],
      ["VITE_SUPABASE_PUBLISHABLE_KEY", status.PUBLISHABLE_KEY],
    ],
  ],
  [
    "Local test user (created by pnpm db:seed)",
    [
      ["DEV_USER_EMAIL", keep("DEV_USER_EMAIL", "dev@tandrix.local")],
      ["DEV_USER_PASSWORD", kept.get("DEV_USER_PASSWORD") || randomBytes(12).toString("base64url")],
    ],
  ],
];

const body = [
  "# Local development. Generated by `pnpm env:local`; safe to edit, re-runs keep your Meta key and secrets.",
  "# Points only at this machine. Production values never belong in this file.",
  ...sections.flatMap(([title, entries]) => [
    "",
    `# ${title}`,
    ...entries.map(([k, v]) => `${k}=${v}`),
  ]),
  "",
].join("\n");

writeFileSync(target, body, { mode: 0o600 });
console.log(
  `Wrote .env.local (Supabase ${apiUrl}, Studio ${status.STUDIO_URL}, mail ${status.MAILPIT_URL ?? status.INBUCKET_URL}).`,
);
// Expo only reads .env files in the app folder, so the phone app gets its own copy with the
// public values only. Nothing secret goes here: EXPO_PUBLIC_* is compiled into the app.
const mobileEnv = join(root, "apps/mobile/.env.local");
const publicEntries = sections
  .flatMap(([, entries]) => entries)
  .filter(([k]) => k.startsWith("EXPO_PUBLIC_"));
writeFileSync(
  mobileEnv,
  [
    "# Phone app, local development. Generated by `pnpm env:local`; public values only.",
    "EXPO_PUBLIC_TANDRIX_ENV=local",
    ...publicEntries.map(([k, v]) => `${k}=${v}`),
    "",
  ].join("\n"),
);
console.log("Wrote apps/mobile/.env.local (public values only).");
if (!kept.get("META_API_KEY"))
  console.log("META_API_KEY is empty: add your dev key to .env.local to use the models.");
