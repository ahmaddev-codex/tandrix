/**
 * Builds the Tandrix icon set from Phosphor (MIT, @phosphor-icons/core) in two styles:
 *   fill    — solid (Phosphor Fill); small inline icons (16 px: chips, buttons, inputs)
 *   outline — Phosphor Regular; standalone icons (20–24 px: cards, banners, notices, gates)
 * Writes src/generated/icons.ts for the web and native components, and the same data into the
 * design system bundle (docs/design/system/components/bundle.js, between the @icons markers).
 * Run with --check to fail when either is out of date (CI).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// The package exports no paths for its SVGs; read them from its folder in this package.
const assets = join(root, "node_modules/@phosphor-icons/core/assets");
const OUT_TS = join(root, "src/generated/icons.ts");
const BUNDLE = join(root, "../../docs/design/system/components/bundle.js");

/** Icons always drawn in outline, even small: their solid forms read too heavy, boxed, or distorted (like reload). */
const outlineOnly = new Set<string>([
  "check",
  "progress",
  "retake",
  "x",
  "plus",
  "menu",
  "expand",
  "actions",
  // Block and caution: a solid one shouts from a chip.
  "stop",
  "alert",
  // Direction: a solid caret is a heavy triangle.
  "chevronDown",
  "chevronLeft",
  "chevronRight",
  "arrowRight",
  "arrowUpRight",
]);

/** Tandrix icon name → Phosphor icon. Names say what the icon means in Tandrix. */
const map = {
  check: "check",
  sealCheck: "seal-check",
  user: "user",
  alert: "warning",
  eyeOff: "eye-slash",
  stop: "prohibit",
  clock: "clock",
  progress: "circle-notch",
  info: "info",
  book: "book-open",
  video: "video-camera",
  camera: "camera",
  monitor: "monitor",
  file: "file-text",
  mic: "microphone",
  power: "power",
  gauge: "gauge",
  arrowRight: "arrow-right",
  chevronLeft: "caret-left",
  chevronRight: "caret-right",
  actions: "list-checks",
  projects: "folder-simple",
  home: "house",
  plus: "plus",
  menu: "list",
  gear: "gear",
  retake: "arrow-counter-clockwise",
  glasses: "eyeglasses",
  laptop: "laptop",
  phone: "device-mobile",
  x: "x",
  pointer: "cursor",
  hand: "hand-pointing",
  image: "image",
  expand: "arrows-out-simple",
  chevronDown: "caret-down",
  arrowUpRight: "arrow-up-right",
  play: "play",
  sun: "sun",
  moon: "moon",
} as const;

type Path = { d: string; o?: number };

function paths(file: string): Path[] {
  const svg = readFileSync(file, "utf8");
  const out: Path[] = [];
  for (const m of svg.matchAll(/<path d="([^"]+)"( opacity="([0-9.]+)")?\s*\/>/g)) {
    out.push(m[3] ? { d: m[1]!, o: Number(m[3]) } : { d: m[1]! });
  }
  if (!out.length) throw new Error(`No paths in ${file}`);
  return out;
}

const data: Record<string, { fill: Path[]; outline: Path[] }> = {};
for (const [name, ph] of Object.entries(map)) {
  const outline = paths(join(assets, "regular", `${ph}.svg`));
  data[name] = {
    fill: outlineOnly.has(name) ? outline : paths(join(assets, "fill", `${ph}-fill.svg`)),
    outline,
  };
}

const json = JSON.stringify(data);
const ts = `// Generated by scripts/build-icons.ts from Phosphor Icons (MIT). Do not edit.
// 256-unit viewBox, filled paths in currentColor; "o" is a path's opacity where it has one.
export type IconWeight = "fill" | "outline";
export interface IconPath {
  d: string;
  o?: number;
}
export const icons: Record<${Object.keys(map)
  .map((k) => JSON.stringify(k))
  .join(" | ")}, Record<IconWeight, IconPath[]>> = ${json};
export type IconName = keyof typeof icons;
`;

const START = "  /* @icons:start (generated by packages/ui/scripts/build-icons.ts) */";
const END = "  /* @icons:end */";
const check = process.argv.includes("--check");
const stale: string[] = [];
const write = (file: string, content: string) => {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {
    // Missing counts as stale.
  }
  if (current === content) return;
  if (check) stale.push(file);
  else writeFileSync(file, content);
};
write(OUT_TS, ts);
// docs/ stays on the machine it was written on, so a clean checkout has no bundle to update.
if (existsSync(BUNDLE)) {
  const bundle = readFileSync(BUNDLE, "utf8");
  const i = bundle.indexOf(START);
  const j = bundle.indexOf(END);
  if (i < 0 || j < 0) throw new Error("bundle.js has no @icons markers");
  write(BUNDLE, `${bundle.slice(0, i)}${START}\n  var ICONS = ${json};\n${bundle.slice(j)}`);
}
if (stale.length) {
  console.error(`Out of date, run pnpm --filter @tandrix/ui build:icons:\n${stale.join("\n")}`);
  process.exit(1);
}
